let i = 61;
while (i <= 100) {
  if (i % 2 === 1) {
    console.log("odd numbers:", i);
  }
  i++;
}

let n = 78;
while (n <= 98) {
  if (n % 2 === 0) {
    console.log("even numbers:", n);
  }
  n++;
}
for (let num = 78; num <= 98; num++) {
  if (num % 2 === 0) {
    console.log("even number", num);
  }
}
for (let numbers = 61; numbers <= 100; numbers++) {
  if (numbers % 2 === 1) {
    console.log("odd number", numbers);
  }
}
